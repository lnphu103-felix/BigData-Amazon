# CELL 1 - ENVIRONMENT SETUP & SPARK SESSION
# ============================================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from pyspark.sql import SparkSession
from pyspark.sql import functions as F
from pyspark.sql.types import DoubleType, IntegerType

# Khởi tạo SparkSession tối ưu bộ nhớ cho Colab
spark = SparkSession.builder \
    .appName("Amazon_Delivery_Time_Prediction") \
    .config("spark.driver.memory", "4g") \
    .config("spark.executor.memory", "4g") \
    .getOrCreate()

print("⚡ PySpark Session khởi tạo thành công!")
print(f"Phiên bản PySpark: {spark.version}")

# Tải file amazon_delivery.csv trực tiếp từ Colab
from google.colab import files
print("\n👉 Vui lòng tải file 'amazon_delivery.csv' lên Colab:")
uploaded = files.upload()

# ============================================================
# CELL 2 - DATA LOADING & CLEANING
# ============================================================
# 1. Đọc dữ liệu CSV bằng PySpark
file_path = list(uploaded.keys())[0] if uploaded else "amazon_delivery.csv"
df = spark.read.csv(file_path, header=True, inferSchema=True)

# 2. Chuẩn hóa tên cột (loại bỏ khoảng trắng)
for col in df.columns:
    df = df.withColumnRenamed(col, col.strip())

# 3. Ép kiểu dữ liệu các cột quan trọng (nếu bị đọc nhầm dạng string)
numeric_candidates = ["Delivery_Time", "Agent_Age", "Agent_Rating", "Distance"]
for col_name in numeric_candidates:
    if col_name in df.columns:
        df = df.withColumn(col_name, F.col(col_name).cast(DoubleType()))

# 4. Loại bỏ giá trị Null / Missing
df = df.dropna()

print(f"Tổng số bản ghi sau khi làm sạch: {df.count()} dòng")
df.printSchema()
df.show(5)

# ============================================================
# CELL 3 - EXPLORATORY DATA ANALYSIS (EDA)
# ============================================================
sns.set_theme(style="whitegrid")
plt.rcParams.update({'font.size': 11})

# Chuyển dữ liệu Spark sang Pandas cho Matplotlib/Seaborn
pdf = df.toPandas()

