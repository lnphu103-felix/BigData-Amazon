# CELL 4 - FEATURE ENGINEERING & PIPELINE
# ============================================================
from pyspark.ml import Pipeline
from pyspark.ml.feature import StringIndexer, OneHotEncoder, VectorAssembler

# Xác định danh sách biến phân loại (Categorical) và biến định lượng (Numerical)
categorical_cols = [c for c in ["Weather", "Traffic", "Vehicle", "Area", "Category"] if c in df.columns]
numerical_cols = [c for c in ["Agent_Age", "Agent_Rating", "Distance"] if c in df.columns]

stages = []

# 1. Mã hóa các biến danh mục (StringIndexer -> OneHotEncoder)
indexed_cols = [f"{c}_index" for c in categorical_cols]
encoded_cols = [f"{c}_vec" for c in categorical_cols]

indexer = StringIndexer(inputCols=categorical_cols, outputCols=indexed_cols, handleInvalid="keep")
encoder = OneHotEncoder(inputCols=indexed_cols, outputCols=encoded_cols)

stages += [indexer, encoder]

# 2. Gom tất cả đặc trưng vào 1 Vector duy nhất bằng VectorAssembler
assembler_inputs = encoded_cols + numerical_cols
assembler = VectorAssembler(inputCols=assembler_inputs, outputCol="features")
stages.append(assembler)

# 3. Khởi tạo Pipeline
pipeline = Pipeline(stages=stages)
pipeline_model = pipeline.fit(df)
prepared_df = pipeline_model.transform(df)

# Chia tập dữ liệu Train (80%) và Test (20%)
train_data, test_data = prepared_df.randomSplit([0.8, 0.2], seed=42)

print(f"Dữ liệu huấn luyện (Train): {train_data.count()} mẫu")
print(f"Dữ liệu kiểm thử (Test): {test_data.count()} mẫu")

# ============================================================
# CELL 5 - MODEL TRAINING & EVALUATION
# ============================================================
from pyspark.ml.regression import LinearRegression, RandomForestRegressor, GBTRegressor
from pyspark.ml.evaluation import RegressionEvaluator

# Khởi tạo các mô hình
models = {
    "Linear Regression": LinearRegression(featuresCol="features", labelCol="Delivery_Time"),
    "Random Forest": RandomForestRegressor(featuresCol="features", labelCol="Delivery_Time", numTrees=50, seed=42),
    "Gradient-Boosted Trees": GBTRegressor(featuresCol="features", labelCol="Delivery_Time", maxIter=30, seed=42)
}

evaluator_rmse = RegressionEvaluator(labelCol="Delivery_Time", predictionCol="prediction", metricName="rmse")
evaluator_r2 = RegressionEvaluator(labelCol="Delivery_Time", predictionCol="prediction", metricName="r2")
evaluator_mae = RegressionEvaluator(labelCol="Delivery_Time", predictionCol="prediction", metricName="mae")

results = []

print("🚀 Đang tiến hành huấn luyện và đánh giá các mô hình...\n")

for name, model in models.items():
    # Fit mô hình
    trained_model = model.fit(train_data)
    predictions = trained_model.transform(test_data)

    # Tính các chỉ số
    rmse = evaluator_rmse.evaluate(predictions)
    r2 = evaluator_r2.evaluate(predictions)
    mae = evaluator_mae.evaluate(predictions)

    results.append({"Model": name, "RMSE": rmse, "R2 Score": r2, "MAE": mae})

# Hiển thị bảng so sánh kết quả
results_df = pd.DataFrame(results)
print("="*50)
print("📊 BẢNG SO SÁNH KẾT QUẢ MÔ HÌNH")
print("="*50)
print(results_df.to_string(index=False))

# Biểu đồ so sánh RMSE giữa các mô hình
plt.figure(figsize=(8, 4))
sns.barplot(data=results_df, x="Model", y="RMSE", palette="viridis")
plt.title("Model Comparison - Root Mean Squared Error (RMSE)", fontsize=13, fontweight='bold')
plt.ylabel("RMSE (Thấp hơn là tốt hơn)")
plt.tight_layout()
plt.show()

# ============================================================
# CELL 6 - FEATURE IMPORTANCE & PREDICTION VISUALIZATION (FIXED)
# ============================================================
# 1. Huấn luyện Random Forest để trích xuất Feature Importance
rf = RandomForestRegressor(featuresCol="features", labelCol="Delivery_Time", numTrees=50, seed=42)
rf_model = rf.fit(train_data)

# 2. Trích xuất mảng tầm quan trọng của đặc trưng
importances = rf_model.featureImportances.toArray()

# 3. Tự động lấy tên chính xác của các cột (bao gồm cả các cột đã qua OneHotEncoder)
try:
    attrs = train_data.schema["features"].metadata["ml_attr"]["attrs"]
    feature_list = []
    for key in ["numeric", "binary", "nominal"]:
        if key in attrs:
            for item in attrs[key]:
                feature_list.append((item["idx"], item["name"]))
    feature_list.sort(key=lambda x: x[0])
    feature_names = [x[1] for x in feature_list]
except Exception:
    feature_names = [f"Feature_{i}" for i in range(len(importances))]

# Đảm bảo khớp độ dài tuyệt đối trước khi đưa vào DataFrame
if len(feature_names) != len(importances):
    feature_names = [f"Feature_{i}" for i in range(len(importances))]

# 4. Tạo DataFrame & Trực quan hóa Feature Importance
feature_importance_df = pd.DataFrame({
    'Feature': feature_names,
    'Importance': importances
}).sort_values(by='Importance', ascending=False)

plt.figure(figsize=(10, 6))
# Hiển thị Top 15 đặc trưng quan trọng nhất
sns.barplot(data=feature_importance_df.head(15), x='Importance', y='Feature', palette='magma')
plt.title("Top Feature Importance Analysis (Random Forest)", fontsize=14, fontweight='bold')
plt.xlabel("Importance Score")
plt.tight_layout()
plt.show()

# 5. Trực quan hóa kết quả dự báo Thực tế vs Dự đoán
predictions = rf_model.transform(test_data)
pred_pd = predictions.select("Delivery_Time", "prediction").limit(200).toPandas()

plt.figure(figsize=(9, 5))
sns.scatterplot(data=pred_pd, x="Delivery_Time", y="prediction", alpha=0.7, color="crimson")
plt.plot([pred_pd["Delivery_Time"].min(), pred_pd["Delivery_Time"].max()],
         [pred_pd["Delivery_Time"].min(), pred_pd["Delivery_Time"].max()], 'k--', lw=2)
plt.title("Actual vs Predicted Delivery Time (Random Forest)", fontsize=14, fontweight='bold')
plt.xlabel("Actual Delivery Time (mins)")
plt.ylabel("Predicted Delivery Time (mins)")
plt.tight_layout()
plt.show()

